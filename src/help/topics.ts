/**
 * 使用帮助的**内容**（与应用逻辑完全分离 ✓：这里只有文字 ✓）。
 *
 * 为什么用结构化块而不是 HTML 字符串 ✗：
 *   - 不用 v-html ✓ → 没有转义与注入问题 ✓；
 *   - 写内容时不必手写标签 ✓ → 少一大类引号/标签不闭合的坑 ✓。
 * 渲染见 components/HelpDialog.vue ✓。
 */
export type HelpBlock =
  | { t: 'p'; v: string }
  | { t: 'h'; v: string }
  | { t: 'ul'; v: string[] }
  | { t: 'ol'; v: string[] }
  | { t: 'note'; v: string }      // 提示框（蓝）
  | { t: 'warn'; v: string }      // 注意框（橙）
  | { t: 'keys'; v: string[] }    // 快捷键行
  | { t: 'img'; v: string; caption?: string }   // 截图（文件在 public/help/<v>.png ✓）

export interface HelpTopic {
  id: string
  /** 章节名（左侧分组 ✓） */
  section: string
  title: string
  /** 搜索用关键词 ✓ */
  tags: string[]
  body: HelpBlock[]
}

const p = (v: string): HelpBlock => ({ t: 'p', v })
const h = (v: string): HelpBlock => ({ t: 'h', v })
const ul = (...v: string[]): HelpBlock => ({ t: 'ul', v })
const ol = (...v: string[]): HelpBlock => ({ t: 'ol', v })
const note = (v: string): HelpBlock => ({ t: 'note', v })
const warn = (v: string): HelpBlock => ({ t: 'warn', v })
const keys = (...v: string[]): HelpBlock => ({ t: 'keys', v })
/** 插图：v = public/help 下的文件名（不带扩展名 ✓），caption 是图注 ✓ */
const img = (v: string, caption?: string): HelpBlock => ({ t: 'img', v, caption })

