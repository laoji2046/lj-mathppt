// 立体几何「复刻图」：把平时试卷 / 讲义里最常出现的那几幅立体几何插图，
// 用「归一化顶点 + 边拓扑 + 顶点字母」按原图逐个描下来，插入后仍然是普通的数学图形元素——
// 点可以拖、线可以改虚实粗细颜色、字母可以改。
//
// 顶点坐标不是"重新画一个"，而是从原图上量出来的：先把线段按原图矢量化，再让每个顶点
// 自动吸附到线条交点（最终对原图黑线的覆盖率 ≥ 0.98），所以插进页面里和原图基本重合。
// 每个预设都带原图宽高比，按建议尺寸插入不会被拉变形。
import type { MathFigureElement } from '@/types'

/** 顶点字母；null = 该顶点不标注 */
type Label = string | null
type Edge = [number, number, 0 | 1]

export interface SolidFigurePreset {
  id: string
  name: string
  /** 出处备注，面板上做 tip 用 */
  note?: string
  /** 建议插入尺寸（与原图宽高比一致） */
  w: number
  h: number
  el: Partial<MathFigureElement>
}

/** 按原图宽高比算一个合适的插入尺寸 */
function box(sw: number, sh: number, maxW = 440, maxH = 470) {
  const s = Math.min(maxW / sw, maxH / sh)
  return { w: Math.round(sw * s), h: Math.round(sh * s) }
}

/**
 * 顶点字母默认贴在顶点正上方 12px；这里统一按「从重心向外推开」再给一点偏移，
 * 让字母落到图形外侧、不压线。d 是期望的推开距离（按插入尺寸的像素算）。
 */
function spread(points: number[], labels: Label[], w: number, h: number, d = 26) {
  const n = points.length / 2
  if (!n) return []
  let cx = 0
  let cy = 0
  for (let i = 0; i < n; i++) { cx += points[i * 2]; cy += points[i * 2 + 1] }
  cx /= n; cy /= n
  return labels.map((lab, i) => {
    if (!lab) return { dx: 0, dy: 0 }
    const ux = points[i * 2] - cx
    const uy = points[i * 2 + 1] - cy
    const len = Math.hypot(ux, uy)
    if (len < 1e-6) return { dx: 0, dy: 0 }
    return { dx: +((ux / len) * d / w).toFixed(4), dy: +((uy / len) * d / h).toFixed(4) }
  })
}

/**
 * 组装一条复刻图：
 * @param sw/sh    原图像素尺寸（只用来定宽高比）
 * @param points   归一化顶点，扁平 [x0,y0,x1,y1,...]
 * @param edges    [起点, 终点, 是否隐藏(1=虚线)]
 * @param labels   顶点字母（_ 下标、^ 上标、' 撇）
 * @param arrows   需要画箭头的边下标（坐标轴用）
 * @param nudge    个别字母的额外手工偏移（像素），用来复刻原图的摆放
 */
function fig(
  id: string, name: string, sw: number, sh: number,
  points: number[], edges: Edge[], labels: Label[],
  opts: { note?: string; arrows?: number[]; nudge?: Record<number, [number, number]> } = {},
): SolidFigurePreset {
  const { w, h } = box(sw, sh)
  const offs = spread(points, labels, w, h)
  if (opts.nudge) {
    for (const [k, v] of Object.entries(opts.nudge)) {
      const i = +k
      const base = offs[i] || { dx: 0, dy: 0 }
      offs[i] = { dx: +(base.dx + v[0] / w).toFixed(4), dy: +(base.dy + v[1] / h).toFixed(4) }
    }
  }
  const arrows = opts.arrows ?? []
  return {
    id, name, note: opts.note, w, h,
    el: {
      kind: sw / sh > 1.05 ? 'pyramid' : 'cube',
      points,
      mesh: { edges: edges as [number, number, number][], faces: [] },
      vlabels: labels,
      labelOffsets: offs,
      edgeStyles: arrows.length
        ? edges.map((_, i) => (arrows.includes(i) ? { arrow: true } : null))
        : undefined,
    },
  }
}

