import { ref } from 'vue'

/**
 * "当前正在编辑的表格单元格"把它的插入函数登记在这里。
 *
 * 为什么需要它：表格编辑时有两个入口能插公式 ——
 *   ① 表格右上角的「∑ 插入公式」（它自己带 sink ✓）
 *   ② 工具栏「公式 ▾ → 预制公式」（原来不带 sink ✗ → 公式变成页面上的元素，落在表格外面 ✗）
 * 用户实际就是这么混用的（截图里既有格子里的公式、也有飘在外面的公式元素 ✓）。
 * 所以这里做一层"全局登记"：只要单元格在编辑，**任何**入口打开公式库都自动落到那个格子。
 */
export const tableCellSink = ref<((latex: string) => void) | null>(null)
